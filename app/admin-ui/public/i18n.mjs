export function resolveLocale(value) {
  if (typeof value !== 'string') return 'en';
  const normalized = value.trim().toLowerCase();
  if (normalized === 'ko' || normalized === 'ko-kr') return 'ko';
  if (normalized === 'en' || normalized === 'en-us') return 'en';
  return 'en';
}

